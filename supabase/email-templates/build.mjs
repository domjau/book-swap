// Builds every automatic email from theme.mjs (look + wording) and shell.mjs (layout).
//   node supabase/email-templates/build.mjs           write the files
//   node supabase/email-templates/build.mjs --check   fail if a file is out of date (used by CI)
// Writes: magic-link.html, confirm-signup.html, change-email.html (paste into Supabase),
//         the generated block in functions/send-notifications/index.ts,
//         preview/*.html (sample data, to look at in a browser).
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { THEME } from './theme.mjs';
import { emailFrame, emailButton, emailCode, emailLangRows, emailEsc } from './shell.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const fnPath = join(here, '../functions/send-notifications/index.ts');
const check = process.argv.includes('--check');
const out = {};

// ---- Supabase sign-in templates ----
export function authTemplate(T, key) {
  const a = T.auth[key], c = T.colors, first = T.langs[0];
  const others = T.langs.slice(1).map((l) => a.title[l]).join(' · ');
  const inner = `
        <p style="margin:0;font-family:${T.font};font-size:24px;font-weight:600;line-height:1.2;color:${c.text}">${a.title[first]}</p>
        <p style="margin:6px 0 22px;font-family:${T.font};font-size:14px;line-height:1.4;color:${c.muted}">${others}</p>${a.showCode ? emailCode(T, '{{ .Token }}') : ''}${emailLangRows(T, a.body, 15)}${a.button ? emailButton(T, a.button.label, a.button.url) : ''}`;
  const footer = T.langs.map((l) => `<span lang="${l}">${T.ignore[l]}</span>`).join('<br>');
  const preheader = (a.showCode ? '{{ .Token }} · ' : '') + T.langs.map((l) => a.title[l]).join(' · ');
  return `<!-- seku seku – Supabase "${a.supabase}" template. Generated by build.mjs from theme.mjs: edit there, not here.
     Paste everything into Supabase → Authentication → Emails → ${a.supabase}. Subject: ${a.subject} -->\n`
    + emailFrame(T, { lang: first, title: a.title.en, preheader, inner, footer });
}
for (const key of Object.keys(THEME.auth)) out[join(here, key + '.html')] = authTemplate(THEME, key);

// ---- Email frame inside the notification function ----
const START = '// >>> generated by supabase/email-templates/build.mjs from theme.mjs + shell.mjs. Do not edit between these lines.';
const END = '// <<< end of generated email frame';
const shellSrc = readFileSync(join(here, 'shell.mjs'), 'utf8').split('\n').filter((l) => !l.startsWith('//')).join('\n').trim();
const block = `${START}\nexport const EMAIL_THEME = ${JSON.stringify({ ...THEME, auth: undefined, ignore: undefined }, null, 2)};\n${shellSrc}\n${END}`;
const fn = readFileSync(fnPath, 'utf8');
const a = fn.indexOf(START), b = fn.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers not found in ' + fnPath);
const newFn = fn.slice(0, a) + block + fn.slice(b + END.length);
out[fnPath] = newFn;

// ---- Previews with sample data ----
const sample = (html) => html.replace(/\{\{ \.Token \}\}/g, '482913').replace(/\{\{ \.NewEmail \}\}/g, 'ana@example.com').replace(/\{\{ \.ConfirmationURL \}\}/g, '#');
for (const key of Object.keys(THEME.auth)) out[join(here, 'preview', key + '.html')] = sample(authTemplate(THEME, key));
// The notification preview needs the function's code: load the new version without its npm imports.
const tmp = join(here, 'preview', '.fn.mjs');
mkdirSync(join(here, 'preview'), { recursive: true });
writeFileSync(tmp, newFn.replace(/^import .*$/gm, ''));
const { buildEmail } = await import(tmp + '?' + Date.now());
const names = { u1: 'Ana', u2: 'Tomas' };
const items = [
  { type: 'request_new', data: { actor: 'u1' } },
  { type: 'message', data: { actor: 'u2', count: 2, snippet: 'Would Saturday work?' } },
  { type: 'wish_match', data: { actor: 'u1', title: 'The Gruffalo', book_id: 'b1' } },
];
for (const lang of ['lt', 'en']) out[join(here, 'preview', `notification-${lang}.html`)] = buildEmail(items, lang, lang === 'lt' ? 'Rūta' : 'Ruth', names, THEME.siteUrl).html;

// ---- Write or check ----
let stale = [];
for (const [p, s] of Object.entries(out)) {
  if (p.endsWith('.fn.mjs')) continue;
  const old = existsSync(p) ? readFileSync(p, 'utf8') : null;
  if (old === s) continue;
  if (check && !p.includes('/preview/')) stale.push(p);
  if (!check) writeFileSync(p, s);
}
try { (await import('node:fs')).unlinkSync(tmp); } catch {}
if (check && stale.length) { console.log('Out of date, run node supabase/email-templates/build.mjs:\n  ' + stale.join('\n  ')); process.exit(1); }
console.log(check ? 'Email files are up to date.' : 'Wrote ' + Object.keys(out).length + ' files.');
void emailEsc;
